    /**
     * Convert markdown headers, lists, and bold text to clean HTML.
     */
    private function convertMarkdownToHtml(string $markdown): string
    {
        if (str_contains($markdown, '<p>') || str_contains($markdown, '<div>') || str_contains($markdown, '<h3>')) {
            return $markdown;
        }

        $lines = explode("\n", $markdown);
        $html = '';
        $inList = false;

        foreach ($lines as $line) {
            $trimmed = trim($line);

            if (empty($trimmed)) {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                continue;
            }

            if (str_starts_with($trimmed, '### ')) {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                $title = htmlspecialchars(substr($trimmed, 4), ENT_QUOTES, 'UTF-8');
                $html .= "<div class=\"sub-heading\">{$title}</div>\n";
            } elseif (str_starts_with($trimmed, '## ')) {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                $title = htmlspecialchars(substr($trimmed, 3), ENT_QUOTES, 'UTF-8');
                $html .= "<div class=\"section-heading\">{$title}</div>\n";
            } elseif (str_starts_with($trimmed, '# ')) {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                $title = htmlspecialchars(substr($trimmed, 2), ENT_QUOTES, 'UTF-8');
                $html .= "<div class=\"section-heading\">{$title}</div>\n";
            } elseif (str_starts_with($trimmed, '- ') || str_starts_with($trimmed, '* ')) {
                if (! $inList) {
                    $html .= "<ul>\n";
                    $inList = true;
                }
                $itemText = substr($trimmed, 2);
                $itemText = $this->formatInlineMarkdown($itemText);
                $html .= "<li>{$itemText}</li>\n";
            } elseif (preg_match('/^\d+\.\s+(.*)$/', $trimmed, $matches)) {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                $itemText = $this->formatInlineMarkdown($matches[1]);
                $html .= "<p><strong>&bull;</strong> {$itemText}</p>\n";
            } else {
                if ($inList) {
                    $html .= "</ul>\n";
                    $inList = false;
                }
                $pText = $this->formatInlineMarkdown($trimmed);
                $html .= "<p>{$pText}</p>\n";
            }
        }

        if ($inList) {
            $html .= "</ul>\n";
        }

        return $html;
    }

    private function formatInlineMarkdown(string $text): string
    {
        $text = preg_replace('/\*\*(.*?)\*\*/', '<strong>$1</strong>', $text);
        $text = preg_replace('/\*([^\*]+)\*/', '<em>$1</em>', $text);
        $text = preg_replace('/`([^`]+)`/', '<code style="background:#f1f5f9;padding:1px 4px;border-radius:3px;font-size:8pt;">$1</code>', $text);

        return $text;
    }
