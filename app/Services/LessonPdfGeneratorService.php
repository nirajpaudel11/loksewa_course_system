    /**
     * Format pure theoretical content, ensuring zero quiz/JSON leakage and enriching short topics with full explanations.
     */
    private function formatPureTheoreticalContent(Lesson $lesson, ?Course $course, $module): string
    {
        $raw = trim($lesson->content ?? '');

        // If content is a JSON string (e.g. from quiz lessons), synthesize topic theory
        $isJson = (str_starts_with($raw, '[') && str_ends_with($raw, ']')) || (str_starts_with($raw, '{') && str_ends_with($raw, '}'));

        // If lesson has genuine extensive theoretical content (e.g. > 300 chars of text/markdown and not JSON)
        if (! empty($raw) && ! $isJson && strlen($raw) > 300) {
            $formatted = $this->convertMarkdownToHtml($raw);

            return <<<HTML
            <div class="section-heading">1. Detailed Syllabus Theory &amp; Subject Matter</div>
            <div class="lesson-text">
                {$formatted}
            </div>
HTML;
        }

        // Generate tailored, deeply explained subject theory for the specific topic
        return $this->generateTailoredTheoryExplanation($lesson, $course, $module);
    }

