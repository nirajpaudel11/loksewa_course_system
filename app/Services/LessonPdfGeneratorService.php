    private static function ensureAutoload(): void
    {
        if (self::$autoloadRegistered) {
            return;
        }

        $cpdfPath = base_path('vendor/dompdf/dompdf/lib/Cpdf.php');
        if (file_exists($cpdfPath) && ! class_exists('Dompdf\Cpdf', false)) {
            require_once $cpdfPath;
        }

        spl_autoload_register(function ($class) {
            $prefixes = [
                'Dompdf\\' => base_path('vendor/dompdf/dompdf/src/'),
                'FontLib\\' => base_path('vendor/dompdf/php-font-lib/src/FontLib/'),
                'Svg\\' => base_path('vendor/dompdf/php-svg-lib/src/Svg/'),
                'Sabberworm\\CSS\\' => base_path('vendor/sabberworm/php-css-parser/src/'),
                'Barryvdh\\DomPDF\\' => base_path('vendor/barryvdh/laravel-dompdf/src/'),
            ];

            foreach ($prefixes as $prefix => $baseDir) {
                $len = strlen($prefix);
                if (strncmp($prefix, $class, $len) !== 0) {
                    continue;
                }

                $relativeClass = substr($class, $len);
                $file = $baseDir.str_replace('\\', '/', $relativeClass).'.php';

                if (file_exists($file)) {
                    require_once $file;

                    return;
                }
            }
        });

        self::$autoloadRegistered = true;
    }

    /**
     * Check if a lesson already has an existing valid attached PDF.
     */
    public function hasValidPdf(Lesson $lesson): bool
    {
        $path = $lesson->attachment_path;
        if (empty($path)) {
            return false;
        }

        if (Str::startsWith($path, ['http://', 'https://'])) {
            return true;
        }

        if (Storage::disk('public')->exists($path)) {
            return true;
        }

        if (file_exists(public_path($path))) {
            return true;
        }

        if (file_exists(public_path('storage/'.$path))) {
            return true;
        }

        return false;
    }

    /**
     * Generate pure theoretical PDFs for all targeted lessons (those generated with lesson_note_* or without PDFs).
     * Preserves all original historical PDFs.
     */
    public function generateMissingLessonPdfs(bool $forceRegenerateGenerated = true): array
    {
        $storageDir1 = public_path('storage/lessons/pdfs');
        $storageDir2 = storage_path('app/public/lessons/pdfs');

        if (! is_dir($storageDir1)) {
            mkdir($storageDir1, 0755, true);
        }
        if (! is_dir($storageDir2)) {
            mkdir($storageDir2, 0755, true);
        }

        $allLessons = Lesson::with(['chapter.module.course', 'module.course'])->orderBy('id')->get();
        $generated = [];
        $skipped = [];

        foreach ($allLessons as $lesson) {
            $isCustomGenerated = Str::startsWith($lesson->attachment_path ?? '', 'lessons/pdfs/lesson_note_');

            // If lesson has an original PDF (not generated by us), keep it completely untouched!
            if (! $isCustomGenerated && $this->hasValidPdf($lesson)) {
                $skipped[] = [
                    'id' => $lesson->id,
                    'title' => $lesson->title,
                    'path' => $lesson->attachment_path,
                ];
                continue;
            }

            // If it already has our generated PDF and we're not forcing regeneration, skip
            if (! $forceRegenerateGenerated && $this->hasValidPdf($lesson)) {
                continue;
            }

            $course = $lesson->course;
            $module = $lesson->module ?? $lesson->chapter?->module;

            $filename = 'lesson_note_'.$lesson->id.'_'.Str::slug(substr($lesson->title, 0, 30)).'.pdf';
            $relativeAttachmentPath = 'lessons/pdfs/'.$filename;
            $fullPath1 = $storageDir1.'/'.$filename;
            $fullPath2 = $storageDir2.'/'.$filename;

            $html = $this->buildPureTheoreticalHtml($lesson, $course, $module);
            $this->renderPdfToFile($html, $fullPath1);

            // Mirror to storage/app/public/lessons/pdfs/
            File::copy($fullPath1, $fullPath2);

            $lesson->update([
                'attachment_path' => $relativeAttachmentPath,
            ]);

            $generated[] = [
                'id' => $lesson->id,
                'title' => $lesson->title,
                'course' => $course?->title ?? 'General Course',
                'file' => $relativeAttachmentPath,
            ];
        }

        return [
            'generated_count' => count($generated),
            'skipped_count' => count($skipped),
            'generated' => $generated,
        ];
    }

    /**
     * Render HTML string directly into PDF file on disk after sanitizing non-ASCII/Devanagari characters.
     */
    private function renderPdfToFile(string $html, string $outputPath): void
    {
        $cleanHtml = $this->sanitizeForDompdf($html);

        $options = new Options;
        $options->set('defaultFont', 'Helvetica');
        $options->set('isHtml5ParserEnabled', true);
        $options->set('isRemoteEnabled', false);

        $dompdf = new Dompdf($options);
        $dompdf->loadHtml($cleanHtml);
        $dompdf->setPaper('A4', 'portrait');
        $dompdf->render();

        file_put_contents($outputPath, $dompdf->output());
    }

    /**
     * Sanitize HTML so that DomPDF's Latin fonts (Helvetica) never produce question marks (????).
     */
    private function sanitizeForDompdf(string $html): string
    {
        // 1. Remove parenthetical Nepali/Devanagari expressions like (पारदर्शिता)
        $html = preg_replace('/\s*\([\x{0900}-\x{097F}\s\/\-,.:;]+\)/u', '', $html);

        // 2. Remove any remaining standalone Devanagari glyphs
        $html = preg_replace('/[\x{0900}-\x{097F}]+/u', '', $html);

        // 3. Clean up empty parentheses
        $html = preg_replace('/\(\s*\)/', '', $html);

        // 4. Normalize double spaces before punctuation
        $html = preg_replace('/\s+([,.;:?!])/', '$1', $html);
        $html = preg_replace('/,\s*,/', ',', $html);

        return $html;
    }

